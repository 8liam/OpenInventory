import { useEffect, useRef, useState } from "react";
import { Button } from "~/components/button/button.component";
import { COPY } from "~/lib/copy/copy.config";
import { postJson } from "~/lib/storage/storage.client";
import { AUTH_STATUS, STORAGE_API } from "~/lib/storage/storage.config";
import { restoreLostFocus } from "~/utils/restore-focus";
import { LOGIN_CARD } from "./login-card.config";
import type { LoginCardProps } from "./login-card.types";

/** The Steam QR sign-in, shared by the first-run screen and the add-account dialog. */
export function LoginCard({
  login,
  title,
  body,
  buttonLabel,
  framed = true,
  headingId,
  bodyId,
  headingLevel = 2,
}: LoginCardProps) {
  const Heading = headingLevel === 1 ? "h1" : "h2";
  const copy = COPY.signIn;
  const [requestError, setRequestError] = useState<string>();

  async function start() {
    setRequestError(undefined);
    try {
      await postJson(STORAGE_API.accountLogin, {});
    } catch (error) {
      setRequestError(error instanceof Error ? error.message : String(error));
    }
  }

  const message = login.status === AUTH_STATUS.error ? login.message : requestError;
  const idle = login.status === AUTH_STATUS.signedOut || login.status === AUTH_STATUS.error;

  // Each step replaces the last (the button gives way to the QR code, the QR code to
  // "connecting", an error brings the button back), so focus on a step that vanished moves to
  // whatever stands in its place, marked as the step's focus target.
  const root = useRef<HTMLDivElement>(null);
  const shownStatus = useRef(login.status);
  useEffect(() => {
    if (shownStatus.current === login.status) return;
    shownStatus.current = login.status;
    restoreLostFocus(root.current?.querySelector<HTMLElement>(LOGIN_CARD.stepSelector));
  }, [login.status]);

  return (
    <div ref={root} className={framed ? LOGIN_CARD.frameClass : undefined}>
      <Heading id={headingId} className={LOGIN_CARD.headingClass}>
        {title}
      </Heading>
      <p id={bodyId} className={LOGIN_CARD.bodyClass}>
        {body}
      </p>
      {login.status === AUTH_STATUS.qrPending && (
        <>
          <div
            {...LOGIN_CARD.stepAttribute}
            role="img"
            aria-label={copy.qrLabel}
            tabIndex={-1}
            className={LOGIN_CARD.qrClass}
            // SVG is generated by our own server from Steam's challenge URL.
            dangerouslySetInnerHTML={{ __html: login.qrSvg }}
          />
          <p className={LOGIN_CARD.waitingClass}>{copy.waiting}</p>
        </>
      )}
      {login.status === AUTH_STATUS.connecting && (
        <p {...LOGIN_CARD.stepAttribute} tabIndex={-1} className={LOGIN_CARD.detailClass}>
          {login.detail}
        </p>
      )}
      {message && (
        <p role="alert" className={LOGIN_CARD.errorClass}>
          {message}
        </p>
      )}
      {idle && (
        <Button
          {...LOGIN_CARD.stepAttribute}
          variant="primary"
          className={LOGIN_CARD.buttonClass}
          onClick={() => void start()}
        >
          {login.status === AUTH_STATUS.error ? COPY.accounts.tryAgain : buttonLabel}
        </Button>
      )}
    </div>
  );
}
