import { useState } from "react";
import { Button } from "~/components/button/button.component";
import { COPY } from "~/lib/copy/copy.config";
import { postJson } from "~/lib/storage/storage.client";
import { AUTH_STATUS, STORAGE_API } from "~/lib/storage/storage.config";
import type { LoginCardProps } from "./login-card.types";

/** The Steam QR sign-in, shared by the first-run screen and the add-account dialog. */
export function LoginCard({ login, title, body, buttonLabel }: LoginCardProps) {
  const copy = COPY.signIn;
  const [requestError, setRequestError] = useState<string>();

  async function start() {
    setRequestError(undefined);
    try {
      await postJson(STORAGE_API.accountLogin, {});
    } catch (error) {
      setRequestError(error instanceof Error ? error.message : String(error));
    }
  }

  const message = login.status === AUTH_STATUS.error ? login.message : requestError;
  const idle = login.status === AUTH_STATUS.signedOut || login.status === AUTH_STATUS.error;

  return (
    <div className="rounded-lg border bg-card p-6">
      <h1 className="text-[15px] font-semibold tracking-tight">{title}</h1>
      <p className="mt-1.5 text-muted-foreground">{body}</p>
      {login.status === AUTH_STATUS.qrPending && (
        <>
          <div
            className="mx-auto mt-5 size-52 rounded-md bg-white p-2 [&>svg]:size-full"
            // SVG is generated by our own server from Steam's challenge URL.
            dangerouslySetInnerHTML={{ __html: login.qrSvg }}
          />
          <p className="mt-3 text-center text-xs text-muted-foreground">{copy.waiting}</p>
        </>
      )}
      {login.status === AUTH_STATUS.connecting && (
        <p className="mt-5 text-muted-foreground">{login.detail}</p>
      )}
      {message && (
        <p role="alert" className="mt-4 text-destructive">
          {message}
        </p>
      )}
      {idle && (
        <Button variant="primary" className="mt-5 w-full" onClick={() => void start()}>
          {login.status === AUTH_STATUS.error ? COPY.accounts.tryAgain : buttonLabel}
        </Button>
      )}
    </div>
  );
}
