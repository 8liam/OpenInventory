import { useState } from "react";
import { Button } from "~/components/button/button.component";
import { Logo } from "~/components/logo/logo.component";
import { COPY } from "~/lib/copy/copy.config";
import { callStorageApi } from "~/lib/storage/storage.client";
import { AUTH_STATUS, STORAGE_API } from "~/lib/storage/storage.config";
import type { SignInScreenProps } from "./sign-in-screen.types";

export function SignInScreen({ auth }: SignInScreenProps) {
  const copy = COPY.signIn;
  const [requestError, setRequestError] = useState<string>();

  async function start() {
    setRequestError(undefined);
    try {
      await callStorageApi(STORAGE_API.qrLogin);
    } catch (error) {
      setRequestError(error instanceof Error ? error.message : String(error));
    }
  }

  const message = auth.status === AUTH_STATUS.error ? auth.message : requestError;
  const idle = auth.status === AUTH_STATUS.signedOut || auth.status === AUTH_STATUS.error;

  return (
    <div className="flex h-dvh items-center justify-center p-6">
      <div className="w-full max-w-sm">
        <Logo className="mb-8 justify-center text-lg" />
        <div className="rounded-lg border bg-card p-6">
          <h1 className="text-[15px] font-semibold tracking-tight">{copy.title}</h1>
          <p className="mt-1.5 text-muted-foreground">{copy.body}</p>
          {auth.status === AUTH_STATUS.qrPending && (
            <div
              className="mx-auto mt-5 size-52 rounded-md bg-white p-2 [&>svg]:size-full"
              // SVG is generated by our own server from Steam's challenge URL.
              dangerouslySetInnerHTML={{ __html: auth.qrSvg }}
            />
          )}
          {auth.status === AUTH_STATUS.qrPending && (
            <p className="mt-3 text-center text-xs text-muted-foreground">{copy.waiting}</p>
          )}
          {auth.status === AUTH_STATUS.connecting && (
            <p className="mt-5 text-muted-foreground">{auth.detail}</p>
          )}
          {message && (
            <p role="alert" className="mt-4 text-destructive">
              {message}
            </p>
          )}
          {idle && (
            <Button variant="primary" className="mt-5 w-full" onClick={() => void start()}>
              {copy.button}
            </Button>
          )}
        </div>
        <p className="mt-4 text-center text-xs text-muted-foreground">{copy.footnote}</p>
      </div>
    </div>
  );
}
