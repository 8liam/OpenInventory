/**
 * Regenerates `data/index.generated.ts`, the list of every community data file, so adding a
 * file needs no code edit: drop the JSON in `data/` and run `pnpm data:build`.
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { z } from "zod";
import { patternFileSchema } from "../src/lib/items/patterns/pattern-file.schema.ts";
import { toPosixPath } from "../src/utils/to-posix-path.ts";
import { attachmentsFileSchema } from "../src/lib/items/attachments/attachments-file.schema.ts";

const DATA_DIR = fileURLToPath(new URL("../data/", import.meta.url));
const PATTERNS_DIR = join(DATA_DIR, "patterns");
const SCHEMA_DIR = join(DATA_DIR, "schema");

function jsonFiles(dir: string): string[] {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const path = join(dir, name);
      return statSync(path).isDirectory() ? jsonFiles(path) : name.endsWith(".json") ? [path] : [];
    });
}

const files = jsonFiles(PATTERNS_DIR).map((path) => `./${toPosixPath(relative(DATA_DIR, path))}`);
const imports = files.map((path, i) => `import f${i} from "${path}" with { type: "json" };`);
const source = `// Generated by \`pnpm data:build\` from the files under data/. Do not edit by hand.
${imports.join("\n")}
import attachments from "./attachments.json" with { type: "json" };

export const PATTERN_FILES: readonly unknown[] = [${files.map((_, i) => `f${i}`).join(", ")}];
export const ATTACHMENTS_FILE: unknown = attachments;
`;
writeFileSync(join(DATA_DIR, "index.generated.ts"), source);

writeFileSync(
  join(SCHEMA_DIR, "pattern-file.schema.json"),
  `${JSON.stringify(z.toJSONSchema(patternFileSchema, { io: "input" }), null, 2)}\n`,
);
writeFileSync(
  join(SCHEMA_DIR, "attachments-file.schema.json"),
  `${JSON.stringify(z.toJSONSchema(attachmentsFileSchema, { io: "input" }), null, 2)}\n`,
);
console.log(`Indexed ${files.length} pattern files.`);
